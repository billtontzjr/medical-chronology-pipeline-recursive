def test_long_transcript_all_parts_read_then_one_summary():
    doc = prepare_document('source.txt', transcript() + '\n' + ('Q. Symptoms?\nA. Pain continued.\n' * 4500) + '\nFINAL TESTIMONY')
    calls = []
    def call(prompt, **kw):
        calls.append(prompt)
        if len(calls) == 1:
            return json.dumps(metadata())
        if 'Extract relevant testimony from this slice' in prompt:
            return json.dumps({'statements': [{'text': 'The witness reported continued pain.',
                'evidence': ['A. Pain continued.']}]})
        return json.dumps(statements())
    entry, evidence = summarize(doc, call)
    assert entry.count('07/16/2026.') == 1
    assert len(calls) == len(source_chunks(doc)) + 2
    assert 'FINAL TESTIMONY' in calls[-2]
    assert evidence['transcript_chars_read'] == len(doc['content'])


def test_batch_isolation_and_unsafe_resume_preserves_files(tmp_path, monkeypatch):
    a = agent()
    docs = [{'filename': 'clinic', 'content': '04/01/2026 clinical'},
            prepare_document('witness.txt', transcript()),
            {'filename': 'clinic2', 'content': '04/02/2026 clinical'}]
    a._read_extracted_files = lambda _: docs
    assert [len(b) for b in a._plan_batches(docs)] == [1, 1, 1]
    old = tmp_path / 'batch_001.md'
    old.write_text('old clinical result')
    with pytest.raises(DepositionReviewRequired, match='predate'):
        a.generate_batches('', str(tmp_path))
    assert old.read_text() == 'old clinical result'


def test_generation_resume_and_source_change(tmp_path):
    a = agent()
    doc = prepare_document('witness.txt', transcript())
    a._read_extracted_files = lambda _: [doc]
    responses = iter([metadata(), statements()])
    a._call_api_with_retry = lambda *a, **k: json.dumps(next(responses))
    assert a.generate_batches('', str(tmp_path))['success']
    assert (tmp_path / 'batch_001.deposition.json').exists()
    a._call_api_with_retry = lambda *a, **k: pytest.fail('Resume must not reprocess')
    assert a.generate_batches('', str(tmp_path))['batches_skipped_from_disk'] == 1
    doc['content'] += '\nNew testimony'
    with pytest.raises(DepositionReviewRequired, match='different sources'):
        a.generate_batches('', str(tmp_path))


def test_assembly_keeps_paragraph_and_evidence(tmp_path):
    a = agent()
    sources, batches, output = [tmp_path / name for name in ('sources', 'batches', 'output')]
    sources.mkdir()
    (sources / 'witness.txt').write_text(transcript())
    responses = iter([metadata(), statements()])
    a._call_api_with_retry = lambda *a, **k: json.dumps(next(responses))
    a.generate_batches(str(sources), str(batches))
    a.extract_header = lambda *a: {'patient_name': 'JAMIE EXAMPLE', 'date_of_birth': '[See Records]', 'date_of_injury': '[See Records]'}
    a.generate_summary_and_gaps = lambda *a: {'summary_md': 'Review testimony.', 'gaps_md': 'Human review required.'}
    a.assemble_outputs(str(sources), str(batches), str(output))
    result = json.loads((output / 'chronology.json').read_text())
    assert result['chronology_markdown'].count('07/16/2026. Jamie Example, Deposition.') == 1
    assert result['deposition_evidence'][0]['source_file'] == 'witness.txt'
    assert result['deposition_evidence'][0]['statements'] == statements()['statements']



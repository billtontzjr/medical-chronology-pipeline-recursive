def test_dates_and_lossless_chunks():
    assert dates_in_text('July 16th, 2026 and APRIL 2ND, 2025 and 02/31/2026') == {'07/16/2026', '04/02/2025'}
    doc = prepare_document('witness.txt', transcript())
    assert ''.join(p['content'] for p in source_chunks(doc, 73)) == doc['content']
    assert cover_dates(prepare_document('witness.txt', transcript() + '\nQ. Previous deposition April 2, 2025?')) == {'07/16/2026'}


def test_one_dated_paragraph_and_retained_evidence():
    calls, responses = [], iter([metadata(), statements()])
    def call(prompt, **kw):
        calls.append(prompt)
        return json.dumps(next(responses))
    doc = prepare_document('witness.txt', transcript())
    entry, evidence = summarize(doc, call)
    assert entry == '07/16/2026. Jamie Example, Deposition. The patient testified that they recalled back pain.'
    assert '\n' not in entry
    assert evidence['statements'] == statements()['statements']
    assert evidence['transcript_sha256'] == doc['transcript_sha256']
    assert 'never separate dated visits' in calls[-1]



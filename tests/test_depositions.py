def test_two_sessions_remain_separate_and_sorted():
    a = agent()
    docs = [prepare_document('july.txt', transcript()),
            prepare_document('april.txt', transcript('April 2nd, 2025'))]
    assert len(a._plan_batches(docs)) == 2
    first = '04/02/2025. Jamie Example, Deposition. The patient reported pain.'
    second = '07/16/2026. Jamie Example, Deposition. The patient recalled treatment.'
    assert a._sort_entries_chronologically(second + '\n\n' + first) == first + '\n\n' + second

def test_verification_all_transcript_parts_and_no_preface(tmp_path):
    a = agent()
    text = 'Deposition Summary\nFALSE PREFACE\nTranscript Text\n' + transcript() + '\n' + 'x' * 85000 + 'FINAL ANSWER'
    source = tmp_path / 'sources'
    source.mkdir()
    (source / 'witness.txt').write_text(text)
    path = tmp_path / 'chronology.md'
    path.write_text('07/16/2026. Jamie Example, Deposition. The patient recalled pain.')
    reviewed = []
    a._verify_entry_batch = lambda e, docs: reviewed.extend(docs) or 'No issues found.'
    result = a.verify_chronology(str(path), str(source))
    assert result['entries_reviewed'] == 1
    assert ''.join(d['content'] for d in reviewed).endswith('FINAL ANSWER')
    assert 'FALSE PREFACE' not in ''.join(d['content'] for d in reviewed)
    assert result['documents_checked'] == 5


